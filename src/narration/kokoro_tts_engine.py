"""
AI Cinematic Story Narrator
Kokoro TTS Engine for narration-only voice generation.
"""

import os
import sys
from pathlib import Path
import numpy as np
import soundfile as sf
import torch

from src.utils.logger import get_logger

log = get_logger(__name__)

# Programmatic configuration of eSpeak path on Windows to avoid Phonemizer error
if sys.platform == "win32":
    espeak_paths = [
        Path("C:/Program Files/eSpeak NG"),
        Path("C:/Program Files (x86)/eSpeak NG"),
    ]
    configured = False
    for base_path in espeak_paths:
        if base_path.exists():
            dll_candidates = [
                base_path / "libespeak-ng.dll",
                base_path / "bin" / "libespeak-ng.dll"
            ]
            for dll_path in dll_candidates:
                if dll_path.exists():
                    os.environ["PHONEMIZER_ESPEAK_LIBRARY"] = str(dll_path)
                    os.environ["PHONEMIZER_ESPEAK_PATH"] = str(base_path)
                    log.info(f"Programmatically set eSpeak-NG library path: {dll_path}")
                    configured = True
                    break
            if configured:
                break
    if not configured:
        log.warning(
            "eSpeak NG directory not detected programmatically. "
            "Please ensure it is installed and added to PATH or environment variables."
        )


class KokoroTTSEngine:
    """
    Wraps Kokoro TTS engine to generate high-quality narration audio.
    """

    def __init__(self, config: dict):
        self.config = config
        tts_cfg = config.get("tts", {})
        self.device = tts_cfg.get("device", "cuda")
        self.lang_code = tts_cfg.get("lang_code", "a")
        self.voice = tts_cfg.get("voice", "am_adam")
        self.speed = tts_cfg.get("speed", 1.0)

        self.output_dir = Path(config["paths"]["output_audio"])
        self.output_dir.mkdir(parents=True, exist_ok=True)

        self._pipeline = None
        self._load_model()

    def _load_model(self) -> None:
        """Loads Kokoro TTS model pipeline onto CUDA/CPU."""
        log.info(f"Initializing Kokoro KPipeline (language: {self.lang_code})...")
        try:
            from kokoro import KPipeline
            
            # Map devices properly
            device_str = "cuda" if self.device == "cuda" and torch.cuda.is_available() else "cpu"
            log.info(f"  Target Device: {device_str}")
            
            self._pipeline = KPipeline(
                lang_code=self.lang_code,
                device=device_str
            )
            log.info("Kokoro KPipeline initialized [OK]")
        except Exception as e:
            log.error(f"Failed to initialize Kokoro KPipeline: {e}")
            raise e

    def generate_narration(self, text: str, output_filename: str, scene_id: int | None = None, voice: str | None = None) -> Path:
        """
        Synthesize audio for a scene or full text using Kokoro pipeline.
        """
        voice_to_use = voice or self.voice
        scene_lbl = f"Scene {scene_id}" if scene_id is not None else "Text"
        log.info(f"  Generating narration for {scene_lbl} using voice '{voice_to_use}'...")

        out_path = self.output_dir / output_filename

        try:
            # Generate chunks
            generator = self._pipeline(text, voice=voice_to_use, speed=self.speed)
            
            # Collect audio chunks
            chunks = []
            for i, (gs, ps, audio) in enumerate(generator):
                if audio is not None:
                    chunks.append(audio)

            if not chunks:
                raise ValueError("No audio data was generated by the Kokoro pipeline.")

            # Concatenate all yielded audio segments
            combined_audio = np.concatenate(chunks)

            # Kokoro sample rate is 24000 Hz
            sf.write(str(out_path), combined_audio, 24000)
            log.info(f"    [OK] Saved: {out_path.name}")
            return out_path

        except Exception as e:
            log.error(f"Synthesis failed: {e}")
            raise e
